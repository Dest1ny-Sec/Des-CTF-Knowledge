#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_idx.py — 从文章标题自动生成 .idx.md 分段索引。

设计原则：
  1. 行号来自真实标题位置，绝不手写。任何内容变动后重跑即可。
  2. 每份索引带源文件 sha256 指纹，供 --check 模式检测漂移。
  3. --check 只校验不写入，退出码非 0 表示索引已过期（可用于 CI / pre-commit）。

用法：
    python3 tools/gen_idx.py            # 重新生成所有 .idx.md
    python3 tools/gen_idx.py --check    # 校验是否过期（CI 用）
    python3 tools/gen_idx.py --file SQL.md

行号约定：L 起止均为 1-based，末端包含该标题块的最后一行（下一个标题前一行）。
"""
import argparse
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# 需要生成索引的源文章（相对仓库根目录）
TARGETS = [
    "SQL.md",
    "命令执行.md",
    "文件上传漏洞.md",
    "文件包含.md",
    "SSRF漏洞.md",
    "PHP反序列化漏洞总结.md",
    "php代码审计.md",
    "JWT.md",
    "SSTI.md",
    "图片隐写.md",
    "音频隐写.md",
    "压缩包总结.md",
]

# 只对 1-3 级标题建索引，4 级以下太碎
MAX_LEVEL = 3

HEADING_RE = re.compile(r"^(#{1,6})\s+(\S.*?)\s*$")


def sha256_of(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def read_lines(path: str):
    with open(path, "rb") as f:
        raw = f.read()
    # 统一换行，避免 CRLF 文件行号偏移
    text = raw.decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")
    return text.split("\n")


def strip_code_fences(lines):
    """返回每行是否位于 ``` 代码块内部（代码块里的 # 不是标题）。

    注意：围栏行本身不计为"代码内容"，只是切换状态。否则紧跟在
    闭合 ``` 之后、没有空行分隔的标题会被误判为代码而丢失。
    """
    inside = [False] * len(lines)
    in_fence = False
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith("```") or s.startswith("~~~"):
            in_fence = not in_fence  # 围栏行只切换状态，不标记为代码
            continue
        inside[i] = in_fence
    return inside


def extract_headings(path: str):
    """返回 [(level, title, start_line, end_line)]，1-based 且末端包含。"""
    lines = read_lines(path)
    in_code = strip_code_fences(lines)

    heads = []
    for i, line in enumerate(lines):
        if in_code[i]:
            continue
        m = HEADING_RE.match(line)
        if not m:
            continue
        level = len(m.group(1))
        if level > MAX_LEVEL:
            continue  # 超过索引层级上限的标题不计入
        title = m.group(2).strip()
        # 去掉标题尾部可能残留的 # 号
        title = re.sub(r"\s*#+\s*$", "", title).strip()
        if not title:
            continue
        heads.append([level, title, i + 1, None])  # 1-based 起始

    total = len(lines)
    for idx, h in enumerate(heads):
        h[3] = total if idx == len(heads) - 1 else heads[idx + 1][2] - 1
    return heads, total


def normalize_anchor(title: str) -> str:
    """GitHub 风格锚点：小写、去标点、空格转连字符。"""
    t = title.lower().strip()
    t = re.sub(r"[`*_\[\]()]", "", t)
    t = re.sub(r"[^\w\u4e00-\u9fff\s\-]", "", t)
    t = re.sub(r"\s+", "-", t)
    return t


def build_index(src_rel: str) -> str:
    src_abs = os.path.join(ROOT, src_rel)
    heads, total = extract_headings(src_abs)
    digest = sha256_of(src_abs)
    base = os.path.basename(src_rel)
    stem = base[:-3] if base.endswith(".md") else base

    out = []
    out.append(f"<!-- AUTO-GENERATED by tools/gen_idx.py — DO NOT EDIT BY HAND -->")
    out.append(f"<!-- source: {base} sha256:{digest} -->")
    out.append(f"# {stem}.idx — 分段索引（自动生成，勿手改）")
    out.append("")
    out.append(f"总行数: {total} | 标题数: {len(heads)} | 源指纹: `{digest[:16]}…`")
    out.append("")
    out.append("> 用法：`Read offset=<起始行> limit=<行数>` 只读目标章节。行号来自真实标题位置。")
    out.append("> 内容变更后执行 `python3 tools/gen_idx.py` 重新生成；`--check` 用于 CI 校验漂移。")
    out.append("")

    # 一级标题概览
    top = [h for h in heads if h[0] <= 2]
    if top:
        out.append("## 章节目录")
        out.append("")
        out.append("| 章节 | 行范围 | 行数 |")
        out.append("|---|---|---|")
        for level, title, start, end in top:
            indent = "" if level == 1 else "└ "
            out.append(f"| {indent}{title} | L{start}-L{end} | {end - start + 1} |")
        out.append("")

    # 完整标题索引（含 3 级）
    out.append("## 完整标题索引")
    out.append("")
    for level, title, start, end in heads:
        indent = "  " * (level - 1)
        anchor = normalize_anchor(title)
        out.append(f"- {indent}[{title}]({base}#{anchor}) → L{start}-L{end}")
    out.append("")

    # 常用检索词
    out.append("## 检索提示")
    out.append("")
    out.append("```bash")
    out.append(f"# 按标题定位")
    out.append(f"grep -n '^#\\\\+ ' {base} | grep '关键词'")
    out.append(f"# 全文搜索（带行号）")
    out.append(f"grep -n '关键词' {base}")
    out.append("```")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验索引是否与源文件一致")
    ap.add_argument("--file", help="只处理指定源文件")
    args = ap.parse_args()

    targets = [args.file] if args.file else TARGETS
    stale, written, missing = [], 0, []

    for rel in targets:
        src = os.path.join(ROOT, rel)
        if not os.path.exists(src):
            missing.append(rel)
            continue
        content = build_index(rel)
        idx_path = os.path.join(ROOT, rel[:-3] + ".idx.md")

        if args.check:
            if not os.path.exists(idx_path):
                stale.append((rel, "索引不存在"))
                continue
            old = open(idx_path, encoding="utf-8").read()
            if old != content:
                stale.append((rel, "内容已漂移"))
            continue

        with open(idx_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        written += 1

    if missing:
        print("⚠ 源文件缺失: " + ", ".join(missing), file=sys.stderr)

    if args.check:
        if stale:
            print("✗ 索引过期（请运行 python3 tools/gen_idx.py）:", file=sys.stderr)
            for rel, why in stale:
                print(f"  - {rel}: {why}", file=sys.stderr)
            return 1
        print(f"✓ 全部索引与源文件一致（{len(targets)} 个）")
        return 0

    print(f"✓ 已生成 {written} 个 .idx.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
